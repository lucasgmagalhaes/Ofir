#!/usr/bin/env python3
"""Generates std/core/num/<type>.at: the methods of each numeric type, as a
`@lang` declaration (ADR 0019), documented as ADR 0020 requires.

Stage 0 has no generic bounds, so each type gets its own copy of the
templates below. Run after editing them:

    python3 tools/gen_core_numbers.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "std" / "core" / "num"
SIGNED = ["i8", "i16", "i32", "i64"]
UNSIGNED = ["u8", "u16", "u32", "u64"]
FLOATS = ["f32", "f64"]
BITS = {"i8": 8, "i16": 16, "i32": 32, "i64": 64, "u8": 8, "u16": 16, "u32": 32, "u64": 64}
GENERATED = "// Generated by tools/gen_core_numbers.py. Do not edit.\n\n"

INT = """
/**
 * The {desc} integer type `{t}`{alias}: values from `{t}.MIN` ({min}) to
 * `{t}.MAX` ({max}).
 *
 * Arithmetic with `+`, `-` and `*` panics on overflow (ADR 0005); the
 * `wrapping` methods wrap around instead, for hashes and checksums.
 */
@lang("{t}")
pub copy struct {t} {{
    /**
     * Adds modulo 2^{bits}: the result wraps around instead of overflowing.
     *
     * @param other the value to add
     * @returns `self + other`, wrapped into the range of `{t}`
     * @example
     * ```astra
     * assert({t}.MAX.wrappingAdd(1) == {t}.MIN)
     * ```
     */
    pub fn wrappingAdd(self, other: {t}) {t} {{
        return wrapping_add_{t}(self, other)
    }}

    /**
     * Subtracts modulo 2^{bits}: the result wraps around instead of
     * overflowing.
     *
     * @param other the value to subtract
     * @returns `self - other`, wrapped into the range of `{t}`
     * @example
     * ```astra
     * assert({t}.MIN.wrappingSub(1) == {t}.MAX)
     * ```
     */
    pub fn wrappingSub(self, other: {t}) {t} {{
        return wrapping_sub_{t}(self, other)
    }}

    /**
     * Multiplies modulo 2^{bits}: the result wraps around instead of
     * overflowing.
     *
     * @param other the factor
     * @returns `self * other`, wrapped into the range of `{t}`
     */
    pub fn wrappingMul(self, other: {t}) {t} {{
        return wrapping_mul_{t}(self, other)
    }}
{abs}
    /**
     * The smaller of two values.
     *
     * @param other the value to compare with
     * @returns `self` if it is not greater than `other`, else `other`
     * @example
     * ```astra
     * assert((3 as {t}).min(5) == 3)
     * ```
     */
    pub fn min(self, other: {t}) {t} {{
        return if other < self {{ other }} else {{ self }}
    }}

    /**
     * The larger of two values.
     *
     * @param other the value to compare with
     * @returns `self` if it is not less than `other`, else `other`
     * @example
     * ```astra
     * assert((3 as {t}).max(5) == 5)
     * ```
     */
    pub fn max(self, other: {t}) {t} {{
        return if other > self {{ other }} else {{ self }}
    }}

    /**
     * Restricts a value to a range.
     *
     * @param lo the smallest result
     * @param hi the largest result; expected to be at least `lo`
     * @returns `lo` if `self < lo`, `hi` if `self > hi`, else `self`
     * @example
     * ```astra
     * assert((12 as {t}).clamp(0, 10) == 10)
     * ```
     */
    pub fn clamp(self, lo: {t}, hi: {t}) {t} {{
        return self.max(lo).min(hi)
    }}

    /**
     * Raises to a power, by repeated squaring: O(log exp) multiplications.
     *
     * @param exp the exponent; `x.pow(0)` is 1
     * @returns `self` multiplied by itself `exp` times
     * @panics when the result does not fit in `{t}`
     * @example
     * ```astra
     * assert((2 as {t}).pow(5) == 32)
     * ```
     */
    pub fn pow(self, exp: u32) {t} {{
        var result: {t} = 1
        var base = self
        var e = exp
        for e > 0 {{
            if e & 1 == 1 {{
                result *= base
            }}
            e >>= 1
            if e > 0 {{
                base *= base
            }}
        }}
        return result
    }}
}}
"""

SIGNED_ABS = """
    /**
     * The absolute value.
     *
     * @returns `-self` for a negative value, else `self`
     * @panics on `{t}.MIN`, whose opposite does not fit in `{t}`
     * @example
     * ```astra
     * assert((-7 as {t}).abs() == 7)
     * ```
     */
    pub fn abs(self) {t} {{
        return if self < 0 {{ -self }} else {{ self }}
    }}
"""

UNSIGNED_ABS = """
    /**
     * The absolute value: an unsigned value is its own.
     *
     * @returns `self`
     */
    pub fn abs(self) {t} {{
        return self
    }}
"""

FLOAT = """
/**
 * The IEEE 754 binary{bits} floating-point type `{t}`{alias}.
 *
 * Arithmetic never panics: it gives infinities and NaN (spec 2.1).
 */
@lang("{t}")
pub copy struct {t} {{
    /**
     * The square root, correctly rounded.
     *
     * @returns the non-negative square root; NaN for a negative value
     * @example
     * ```astra
     * assert((9.0 as {t}).sqrt() == 3.0)
     * ```
     */
    pub fn sqrt(self) {t} {{
        return sqrt_{t}(self)
    }}

    /**
     * The absolute value.
     *
     * @returns `self` without its sign
     */
    pub fn abs(self) {t} {{
        return fabs_{t}(self)
    }}

    /**
     * Rounds down.
     *
     * @returns the largest integral value not greater than `self`
     * @example
     * ```astra
     * assert((-1.5 as {t}).floor() == -2.0)
     * ```
     */
    pub fn floor(self) {t} {{
        return floor_{t}(self)
    }}

    /**
     * Rounds up.
     *
     * @returns the smallest integral value not less than `self`
     * @example
     * ```astra
     * assert((1.2 as {t}).ceil() == 2.0)
     * ```
     */
    pub fn ceil(self) {t} {{
        return ceil_{t}(self)
    }}

    /**
     * The smaller of two values.
     *
     * @param other the value to compare with
     * @returns the smaller value; when one of them is NaN, the other one
     */
    pub fn min(self, other: {t}) {t} {{
        return minnum_{t}(self, other)
    }}

    /**
     * The larger of two values.
     *
     * @param other the value to compare with
     * @returns the larger value; when one of them is NaN, the other one
     */
    pub fn max(self, other: {t}) {t} {{
        return maxnum_{t}(self, other)
    }}

    /**
     * Whether the value is NaN, the only value not equal to itself.
     *
     * @returns true for NaN
     */
    pub fn isNan(self) bool {{
        return self != self
    }}
}}
"""


def intrinsics(t: str, ops: list[tuple[str, int]]) -> str:
    lines = ["// The operations the compiler generates for this type (ADR 0019).",
             'extern "intrinsic" {']
    for op, arity in ops:
        params = ", ".join(f"{p}: {t}" for p in "ab"[:arity])
        lines.append(f"    fn {op}_{t}({params}) {t}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def module_doc(t: str) -> str:
    return f"/**\n * @module\n * The methods of `{t}` (docs/std/core.md).\n */\n\n"


def int_file(t: str) -> str:
    bits = BITS[t]
    signed = t in SIGNED
    lo = -(1 << (bits - 1)) if signed else 0
    hi = (1 << (bits - 1)) - 1 if signed else (1 << bits) - 1
    alias = {"i64": " (`int`)", "u64": " (`uint`)"}.get(t, "")
    abs_text = (SIGNED_ABS if signed else UNSIGNED_ABS).format(t=t)
    body = INT.format(t=t, abs=abs_text, bits=bits, alias=alias, min=lo, max=hi,
                      desc=f"{bits}-bit {'signed' if signed else 'unsigned'}")
    ops = [("wrapping_add", 2), ("wrapping_sub", 2), ("wrapping_mul", 2)]
    return module_doc(t) + GENERATED + intrinsics(t, ops) + body


def float_file(t: str) -> str:
    alias = " (`float`)" if t == "f64" else ""
    ops = [("sqrt", 1), ("fabs", 1), ("floor", 1), ("ceil", 1), ("minnum", 2), ("maxnum", 2)]
    return module_doc(t) + GENERATED + intrinsics(t, ops) + FLOAT.format(
        t=t, bits=t[1:], alias=alias)


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    for t in SIGNED + UNSIGNED:
        (OUT / f"{t}.at").write_text(int_file(t))
    for t in FLOATS:
        (OUT / f"{t}.at").write_text(float_file(t))
