#!/usr/bin/env python3
"""Generates std/core/ints.at and std/core/floats.at: the methods of the
numeric types, one `@lang` declaration per type (ADR 0019).

Stage 0 has no generic bounds, so each type gets its own copy; the
template is below. Run after editing it:

    python3 tools/gen_core_numbers.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SIGNED = ["i8", "i16", "i32", "i64"]
UNSIGNED = ["u8", "u16", "u32", "u64"]
HEADER = "// Generated by tools/gen_core_numbers.py. Do not edit.\n"

INT = """
@lang("{t}")
pub copy struct {t} {{
    /// Addition modulo 2^bits: never panics.
    pub fn wrappingAdd(self, other: {t}) {t} {{
        return wrapping_add_{t}(self, other)
    }}

    pub fn wrappingSub(self, other: {t}) {t} {{
        return wrapping_sub_{t}(self, other)
    }}

    pub fn wrappingMul(self, other: {t}) {t} {{
        return wrapping_mul_{t}(self, other)
    }}
{abs}
    pub fn min(self, other: {t}) {t} {{
        return if other < self {{ other }} else {{ self }}
    }}

    pub fn max(self, other: {t}) {t} {{
        return if other > self {{ other }} else {{ self }}
    }}

    pub fn clamp(self, lo: {t}, hi: {t}) {t} {{
        return self.max(lo).min(hi)
    }}

    /// `self` to the power `exp`; panics on overflow.
    pub fn pow(self, exp: u32) {t} {{
        var result: {t} = 1
        var base = self
        var e = exp
        for e > 0 {{
            if e & 1 == 1 {{
                result *= base
            }}
            e >>= 1
            if e > 0 {{
                base *= base
            }}
        }}
        return result
    }}
}}
"""

SIGNED_ABS = """
    /// Panics on the minimum value, whose opposite does not fit.
    pub fn abs(self) {t} {{
        return if self < 0 {{ -self }} else {{ self }}
    }}
"""

UNSIGNED_ABS = """
    pub fn abs(self) {t} {{
        return self
    }}
"""

FLOAT = """
@lang("{t}")
pub copy struct {t} {{
    pub fn sqrt(self) {t} {{
        return sqrt_{t}(self)
    }}

    pub fn abs(self) {t} {{
        return fabs_{t}(self)
    }}

    pub fn floor(self) {t} {{
        return floor_{t}(self)
    }}

    pub fn ceil(self) {t} {{
        return ceil_{t}(self)
    }}

    /// The smaller value; a NaN operand gives the other one.
    pub fn min(self, other: {t}) {t} {{
        return minnum_{t}(self, other)
    }}

    pub fn max(self, other: {t}) {t} {{
        return maxnum_{t}(self, other)
    }}

    pub fn isNan(self) bool {{
        return self != self
    }}
}}
"""


def intrinsics(types: list[str], ops: list[tuple[str, int]]) -> str:
    lines = ['extern "intrinsic" {']
    for t in types:
        for op, arity in ops:
            params = ", ".join(f"{p}: {t}" for p in "ab"[:arity])
            lines.append(f"    fn {op}_{t}({params}) {t}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def ints() -> str:
    out = [HEADER, "//! The methods of the integer types (docs/std/core.md).\n\n"]
    out.append(intrinsics(SIGNED + UNSIGNED, [("wrapping_add", 2), ("wrapping_sub", 2),
                                              ("wrapping_mul", 2)]))
    for t in SIGNED + UNSIGNED:
        abs_text = (SIGNED_ABS if t in SIGNED else UNSIGNED_ABS).format(t=t)
        out.append(INT.format(t=t, abs=abs_text))
    return "".join(out)


def floats() -> str:
    out = [HEADER, "//! The methods of the float types (docs/std/core.md).\n\n"]
    out.append(intrinsics(["f32", "f64"], [("sqrt", 1), ("fabs", 1), ("floor", 1), ("ceil", 1),
                                           ("minnum", 2), ("maxnum", 2)]))
    out += [FLOAT.format(t=t) for t in ["f32", "f64"]]
    return "".join(out)


if __name__ == "__main__":
    (ROOT / "std" / "core" / "ints.at").write_text(ints())
    (ROOT / "std" / "core" / "floats.at").write_text(floats())
